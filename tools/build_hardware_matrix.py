#!/usr/bin/env python3
"""Generate appendix_d_hardware_matrix.md from assets/data/isas.json (the single source of truth).

    python tools/build_hardware_matrix.py
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
rows = json.load(open(os.path.join(ROOT, "assets", "data", "isas.json")))
rows.sort(key=lambda r: (r["year"], r["name"]))
yn = lambda b: "yes" if b else "no"


def esc(s):
    return str(s).replace("|", "\\|")


out = ["---", 'title: "Appendix D — Hardware Matrix"', "---", "",
       "[← Back to Table of Contents](./README.md)", "", "# Appendix D — Hardware Matrix", "",
       "> *Generated by `tools/build_hardware_matrix.py` from `assets/data/isas.json`. Do not edit by hand;",
       "> edit the JSON and regenerate. The same rows drive the interactive [Vector ISA Atlas](./atlas.md).*", "",
       "## Overview", "",
       "Every vector instruction set and matrix engine in the book, oldest first. *Bits* is the register width for",
       "fixed SIMD, the architectural maximum for vector-length-agnostic ISAs, and the operand footprint of one",
       "operation for matrix engines (see each row's note). Rows marked unconfirmed rely on secondary sources.", "",
       "---", "", "## Capabilities", "",
       "| Name | Vendor | Kind | Year | Bits | VLA | Masking | Gather | Scatter |",
       "|---|---|---|:---:|:---:|:---:|---|:---:|:---:|"]
for r in rows:
    out.append(f"| **{esc(r['name'])}** | {esc(r['vendor'])} | {esc(r['kind'])} | {r['year']} | {r['width_bits']} | "
               f"{yn(r['vla'])} | {esc(r['predication'])} | {yn(r['gather'])} | {yn(r['scatter'])} |")
out += ["", "---", "", "## ML data types, matrix shapes and first silicon", "",
        "| Name | ML data types | Matrix operation | First silicon |", "|---|---|---|---|"]
for r in rows:
    out.append(f"| **{esc(r['name'])}** | {esc(r['ml_types'])} | {esc(r['matrix']) or '—'} | {esc(r['first_silicon'])} |")
out += ["", "---", "", "## Notes and sources", "", "| Name | Note | Source |", "|---|---|---|"]
for r in rows:
    out.append(f"| **{esc(r['name'])}** | {esc(r['note'])} | {esc(r['source'])} |")
out += ["", "---", "", "**Next:** [Appendix E — Bibliography](./appendix_e_bibliography.md) — the reading list by theme.", ""]
open(os.path.join(ROOT, "appendix_d_hardware_matrix.md"), "w").write("\n".join(out))
print(f"wrote appendix_d_hardware_matrix.md ({len(rows)} rows)")
